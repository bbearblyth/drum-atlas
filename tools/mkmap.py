def inside(x,y,poly):
    c=False; n=len(poly)
    for i in range(n):
        x1,y1=poly[i]; x2,y2=poly[(i+1)%n]
        if (y1>y)!=(y2>y) and x < (x2-x1)*(y-y1)/(y2-y1)+x1: c=not c
    return c
taken=set(); out={k:[] for k in list(P)+list(MANUAL)}
order=['UK','CAR','NA','LAT','EUR','MENA','WAF','SAF','SAS','EAS','OTHER']
def cell(lon,lat): return (round((lon-LON0)/STEP), round((LAT0-lat)/STEP))
for k in order:
    for lon,lat in MANUAL.get(k,[]):
        c=cell(lon,lat)
        if c not in taken: taken.add(c); out[k].append(c)
    for poly in P.get(k,[]):
        for cx in range(COLS+1):
            for cy in range(ROWS+1):
                lon=LON0+cx*STEP; lat=LAT0-cy*STEP
                if (cx,cy) not in taken and inside(lon,lat,poly):
                    taken.add((cx,cy)); out[k].append((cx,cy))
enc={k:';'.join(f'{x},{y}' for x,y in sorted(v)) for k,v in out.items()}
js='/* Stylised dot-matrix world map for the area filter. Generated; grid units, '+f'{COLS+1}x{ROWS+1}'+'. */\n'
js+='window.MAP_GRID = '+json.dumps({'w':COLS+1,'h':ROWS+1})+';\nwindow.MAP_DOTS = '+json.dumps(enc)+';\n'
